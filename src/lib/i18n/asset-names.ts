const HAS_CYRILLIC = /[А-Яа-яЁё]/;

/** Display name of an asset in the page language: Russian as stored; en/zh from the table, else the ticker. */
export function assetName(asset: { slug: string; name: string; instruments?: { ticker?: string | null }[] | null }, locale: Locale | string): string {
  if (locale === "ru") return asset.name;
  const hit = NAMES[asset.slug];
  if (hit) return locale === "cn" ? hit[1] ?? hit[0] : hit[0];
  if (!HAS_CYRILLIC.test(asset.name)) return asset.name;
  return asset.instruments?.[0]?.ticker || asset.slug.toUpperCase();
}
