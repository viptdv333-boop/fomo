export interface Item {
  /** local date YYYY-MM-DD in the issuer's zone */
  d: string;
  /** local clock time HH:MM (series.tz), overrides series.t */
  t?: string;
  /** period label appended to the title (ru / en) */
  q?: string;
  qe?: string;
  /** approximate date (rule of thumb) */
  a?: boolean;
  /** the issuer calls the date tentative */
  tent?: boolean;
  /** importance override */
  imp?: 1 | 2 | 3;
}

