/* ───────────── calendar arithmetic (dates are YYYY-MM-DD strings, zone independent) ───────────── */

const dow = (d: string): number => new Date(`${d}T00:00:00Z`).getUTCDay(); // 0 Sunday
const iso = (y: number, m: number, d: number): string => new Date(Date.UTC(y, m - 1, d)).toISOString().slice(0, 10);

function nthWeekday(y: number, m: number, wd: number, n: number): string {
  const first = dow(iso(y, m, 1));
  return iso(y, m, 1 + ((wd - first + 7) % 7) + (n - 1) * 7);
}
function lastWeekday(y: number, m: number, wd: number): string {
  const last = addDays(iso(y, m + 1, 1), -1);
  return addDays(last, -((dow(last) - wd + 7) % 7));
}

/** US federal holidays as observed (a Saturday holiday is observed on Friday, a Sunday one on Monday), years y-1..y+1 merged. */
export function usFederalHolidays(y: number): Set<string> {
  const out = new Set<string>();
  for (const yy of [y - 1, y, y + 1]) {
    const fixed = [iso(yy, 1, 1), iso(yy, 6, 19), iso(yy, 7, 4), iso(yy, 11, 11), iso(yy, 12, 25)];
    for (const f of fixed) out.add(dow(f) === 6 ? addDays(f, -1) : dow(f) === 0 ? addDays(f, 1) : f);
    out.add(nthWeekday(yy, 1, 1, 3)); // Martin Luther King Jr. Day
    out.add(nthWeekday(yy, 2, 1, 3)); // Presidents Day
    out.add(lastWeekday(yy, 5, 1)); // Memorial Day
    out.add(nthWeekday(yy, 9, 1, 1)); // Labor Day
    out.add(nthWeekday(yy, 10, 1, 2)); // Columbus Day
    out.add(nthWeekday(yy, 11, 4, 4)); // Thanksgiving
  }
  return out;
}

