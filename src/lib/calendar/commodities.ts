const cpImpact = (d: string): 1 | 2 => (+d.slice(5, 7) >= 6 && +d.slice(5, 7) <= 9 ? 2 : 1);

/** Crop Progress of a season not yet in the NASS calendar: Mondays from the first Monday of April to the last Monday of November, a holiday Monday moves to Tuesday (rule seen in 2020-2026). */
export function cropProgressRule(year: number): Item[] {
  const out: Item[] = [];
  const first = nthWeekday(year, 4, 1, 1);
  const last = lastWeekday(year, 11, 1);
  const hol = usFederalHolidays(year);
  for (let d = first; d <= last; d = addDays(d, 7)) {
    const when = hol.has(d) ? addDays(d, 1) : d;
    out.push({ d: when, a: true, imp: cpImpact(when) });
  }
  return out;
}

/** Export Sales: Thursdays 08:30 ET (FAS: «unless a change is announced»); when the Friday before or Monday-Thursday of the release week is a federal holiday the summary comes out on Friday. */
export function exportSalesRule(from: string, to: string): Item[] {
  const out: Item[] = [];
  let d = from;
  while (dow(d) !== 4) d = addDays(d, 1);
  const hol = new Set<string>([...usFederalHolidays(+from.slice(0, 4)), ...usFederalHolidays(+to.slice(0, 4))]);
  for (; d <= to; d = addDays(d, 7)) {
    const shifted = [-6, -3, -2, -1, 0].some((k) => hol.has(addDays(d, k)));
    // the Friday itself may be a holiday (Dec 31 -> Jan 1): then the Thursday stays, but the date is a guess
    out.push(shifted ? { d: hol.has(addDays(d, 1)) ? d : addDays(d, 1), a: true } : { d });
  }
  return out;
}

/* ───────────── monthly rules (approx) ───────────── */

const MONTHS_RU = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"];
const MONTHS_EN = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

const nextWeekday = (d: string): string => {
  let x = d;
  while (dow(x) === 0 || dow(x) === 6) x = addDays(x, 1);
  return x;
};

/** MPOB publishes on about the 10th of the month (a weekend moves to Monday); the data are those of the previous month. Future months only. */
function mpobRule(from: string, to: string): Item[] {
  const out: Item[] = [];
  for (let y = +from.slice(0, 4); y <= +to.slice(0, 4); y++) {
    for (let m = 1; m <= 12; m++) {
      const d = nextWeekday(iso(y, m, 10));
      if (d < from || d > to) continue;
      const prev = (m + 10) % 12;
      out.push({ d, a: true, q: `за ${MONTHS_RU[prev]}`, qe: `${MONTHS_EN[prev]} data` });
    }
  }
  return out;
}

/** Cargo-surveyor export data (ITS / AmSpec) of the 1st-10th, 1st-15th, 1st-20th and 1st-25th of the month: published the same evening / next morning, no official calendar. */
function cargoRule(from: string, to: string): Item[] {
  const out: Item[] = [];
  for (let y = +from.slice(0, 4); y <= +to.slice(0, 4); y++) {
    for (let m = 1; m <= 12; m++) {
      for (const day of [10, 15, 20, 25]) {
        const d = nextWeekday(iso(y, m, day));
        if (d < from || d > to) continue;
        out.push({ d, a: true, q: `1–${day} числа`, qe: `1st-${day}th` });
      }
    }
  }
  return out;
}

