/* ───────────── building events ───────────── */

export function wallToUtc(date: string, hm: string, zone: string): number {
  const [y, m, d] = date.split("-").map(Number);
  const [h, mi] = hm.split(":").map(Number);
  const wall = Date.UTC(y, m - 1, d, h, mi);
  let ts = wall - tzOffsetMs(wall, zone);
  ts = wall - tzOffsetMs(ts, zone); // second pass settles the DST edge
  return ts;
}

export interface ScheduledItem {
  series: string;
  gk: string;
  /** local date in the issuer's zone */
  date: string;
  ts: number;
  allDay: boolean;
  approx: boolean;
  tentative: boolean;
  impact: 1 | 2 | 3;
  src: string;
  tz: string;
  time: string | null;
}

/** The raw schedule (for the check script): every item with its instant, importance and exactness. */
export function commoditySchedule(): ScheduledItem[] {
  const out: ScheduledItem[] = [];
  for (const s of SERIES) {
    for (const it of s.items) {
      const hm = it.t ?? s.t ?? null;
      const allDay = !s.tz || !hm;
      const ts = allDay ? Date.parse(`${it.d}T00:00:00Z`) : wallToUtc(it.d, hm!, s.tz);
      const base = it.imp ?? s.impact;
      out.push({ series: s.id, gk: s.gk, date: it.d, ts, allDay, approx: !!it.a, tentative: !!it.tent, impact: (it.a ? Math.min(base, 2) : base) as 1 | 2 | 3, src: s.src, tz: s.tz, time: allDay ? null : hm, });
    }
  }
  return out.sort((a, b) => a.ts - b.ts);
}

const SUFFIX = { ru: " (ориентировочно)", en: " (approx.)" } as const;

function buildAll(lang: "ru" | "en"): CalEvent[] {
  const out: CalEvent[] = [];
  for (const s of SERIES) {
    for (const it of s.items) {
      const hm = it.t ?? s.t ?? null;
      const allDay = !s.tz || !hm;
      const ts = allDay ? Date.parse(`${it.d}T00:00:00Z`) : wallToUtc(it.d, hm!, s.tz);
      const q = lang === "ru" ? it.q : it.qe;
      const title = `${lang === "ru" ? s.ru : s.en}${q ? `, ${q}` : ""}${it.a ? SUFFIX[lang] : ""}`;
      const flags =
        lang === "ru"
          ? `${it.a ? "Дата ориентировочная: выведена по правилу, издатель её заранее не объявлял. " : ""}${it.tent ? "Дата объявлена организацией как предварительная. " : ""}`
          : `${it.a ? "Approximate date: derived from a rule, not announced by the issuer. " : ""}${it.tent ? "The issuer calls this date tentative. " : ""}`;
      const base = it.imp ?? s.impact;
      out.push({
        id: eventId(ts, s.country, title),
        ts,
        allDay,
        country: s.country,
        currency: s.currency,
        event: title,
        category: "commodity",
        impact: (it.a ? Math.min(base, 2) : base) as 1 | 2 | 3,
        actual: null,
        forecast: null,
        previous: null,
        unit: null,
        change: null,
        changePercentage: null,
        description: `${lang === "ru" ? s.noteRu : s.noteEn} ${flags}${lang === "ru" ? "Источник" : "Source"}: ${s.src}`,
        hasDesc: true,
        period: q,
        origin: s.org,
        gk: s.gk,
        tags: s.tags,
      });
    }
  }
  return out.sort((a, b) => a.ts - b.ts || b.impact - a.impact || a.event.localeCompare(b.event));
}

const built: Partial<Record<"ru" | "en", CalEvent[]>> = {};

/** Commodity / agriculture events with UTC dates in [from, to] (inclusive). Titles are Russian for lang "ru", English otherwise. Pure, never throws. */
export function buildCommodityEvents(from: string, to: string, lang: CommodityLang = "ru"): CalEvent[] {
  const l = lang === "ru" ? "ru" : "en";
  let all = built[l];
  if (!all) all = built[l] = buildAll(l);
  return all.filter((e) => {
    const d = new Date(e.ts).toISOString().slice(0, 10);
    return d >= from && d <= to;
  });
}

/* ───────────── de-duplication against the TradingView feed ───────────── */

/** TradingView names the official layer replaces: when both carry the report on the same UTC day, the official one stays. */
const FEED_DUPLICATES: [RegExp, string][] = [
  [/^WASDE Report$/i, "agro.wasde"],
  [/^Quarterly Grain Stocks\b/i, "agro.grainstocks"],
];

/** Removes feed events (raw English names) that the commodity layer already covers (same report, same UTC day). */
export function dropOfficialDuplicates(main: readonly CalEvent[], commodity: readonly CalEvent[]): CalEvent[] {
  if (commodity.length === 0) return main.slice();
  const have = new Set(commodity.map((e) => `${e.gk}|${new Date(e.ts).toISOString().slice(0, 10)}`));
  return main.filter((e) => {
    const day = new Date(e.ts).toISOString().slice(0, 10);
    return !FEED_DUPLICATES.some(([re, gk]) => re.test(e.event.trim()) && have.has(`${gk}|${day}`));
  });
}
