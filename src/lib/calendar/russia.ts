const MONTH_NOM = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"];
const MONTH_GEN = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"];
const MONTH_EN = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const MON_EN = MONTH_EN.map((m) => m.slice(0, 3));

/**
 * Period code -> label (ru, en):
 *   M2026-09 a month, C2026-01..09 January-September cumulative, Q2026-2 a quarter, H2026-1 a half-year, Y2025 a year ("Y2025r": revised),
 *   D2026-10-01 «as of» a date, W2026-01-01~2026-01-12 a week (weekly CPI).
 */
export function periodLabel(code: string, lang: "ru" | "en"): string {
  const ru = lang === "ru";
  let m = /^M(\d{4})-(\d{2})$/.exec(code);
  if (m) return ru ? `${MONTH_NOM[+m[2] - 1]} ${m[1]}` : `${MONTH_EN[+m[2] - 1]} ${m[1]}`;
  m = /^C(\d{4})-(\d{2})\.\.(\d{2})$/.exec(code);
  if (m) return ru ? `январь–${MONTH_NOM[+m[3] - 1]} ${m[1]}` : `Jan–${MON_EN[+m[3] - 1]} ${m[1]}`;
  m = /^Q(\d{4})-(\d)$/.exec(code);
  if (m) return ru ? `${m[2]} кв. ${m[1]}` : `Q${m[2]} ${m[1]}`;
  m = /^H(\d{4})-(\d)$/.exec(code);
  if (m) return ru ? `${m[2]} п/г ${m[1]}` : `H${m[2]} ${m[1]}`;
  m = /^Y(\d{4})(r?)$/.exec(code);
  if (m) return ru ? `${m[1]} год${m[2] ? ", уточнённая оценка" : ""}` : `${m[1]}${m[2] ? ", revised" : ""}`;
  m = /^D(\d{4})-(\d{2})-(\d{2})$/.exec(code);
  if (m) return ru ? `на ${+m[3]} ${MONTH_GEN[+m[2] - 1]} ${m[1]}` : `as of ${MON_EN[+m[2] - 1]} ${+m[3]}, ${m[1]}`;
  m = /^W(\d{4})-(\d{2})-(\d{2})~(\d{4})-(\d{2})-(\d{2})$/.exec(code);
  if (m) {
    const [d1, m1, d2, m2] = [+m[3], +m[2], +m[6], +m[5]];
    if (ru) return m1 === m2 ? `${d1}–${d2} ${MONTH_GEN[m2 - 1]}` : `${d1} ${MONTH_GEN[m1 - 1]} – ${d2} ${MONTH_GEN[m2 - 1]}`;
    return m1 === m2 ? `${MON_EN[m2 - 1]} ${d1}–${d2}` : `${MON_EN[m1 - 1]} ${d1} – ${MON_EN[m2 - 1]} ${d2}`;
  }
  return "";
}

/* ───────────── calendar arithmetic (YYYY-MM-DD strings) ───────────── */

const dow = (d: string): number => new Date(`${d}T00:00:00Z`).getUTCDay(); // 0 Sunday
const iso = (y: number, m: number, d: number): string => new Date(Date.UTC(y, m - 1, d)).toISOString().slice(0, 10);

function lastWednesday(y: number, m: number): string {
  const last = addDays(iso(y, m + 1, 1), -1);
  return addDays(last, -((dow(last) - 3 + 7) % 7));
}

/** Rosstat's weekly CPI estimate comes out every Wednesday (the 2027 schedule is not published yet): the rule for [from, to]. */
export function weeklyCpiRule(from: string, to: string): Item[] {
  const out: Item[] = [];
  let d = from;
  while (dow(d) !== 3) d = addDays(d, 1);
  for (; d <= to; d = addDays(d, 7)) out.push({ d, a: true });
  return out;
}

/** Inflation expectations of the Bank of Russia: 2026 dates were Jun 24, Jul 28, Aug 26, Sep 29, Oct 28 (a Tue / Wed in the last week of the month): the last Wednesday. */
export function inflExpRule(from: string, to: string): Item[] {
  const out: Item[] = [];
  for (let y = +from.slice(0, 4); y <= +to.slice(0, 4); y++) {
    for (let m = 1; m <= 12; m++) {
      const d = lastWednesday(y, m);
      if (d >= from && d <= to) out.push({ d, a: true, p: `M${y}-${String(m).padStart(2, "0")}` });
    }
  }
  return out;
}

const items = (list: string, extra: Partial<Item> = {}): Item[] => list.split(/\s+/).filter(Boolean).map((d) => ({ d, ...extra }));
/** "2026-10-07:D2026-10-01 ..." -> items with a period code */
const withP = (list: string): Item[] =>
  list.split(/\s+/).filter(Boolean).map((s) => {
    const [d, p] = s.split(":");
    return { d, p };
  });

