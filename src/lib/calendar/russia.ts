const SUFFIX = { ru: " (ориентировочно)", en: " (approx.)" } as const;

export function toTs(date: string, hm: string): { ts: number; allDay: boolean } {
  const [y, m, d] = date.split("-").map(Number);
  if (!hm) return { ts: Date.UTC(y, m - 1, d), allDay: true };
  const [h, mi] = hm.split(":").map(Number);
  return { ts: Date.UTC(y, m - 1, d, h - 3, mi), allDay: false }; // MSK = UTC+3
}

export interface RuScheduled {
  series: string;
  gk: string;
  date: string;
  ts: number;
  allDay: boolean;
  approx: boolean;
  impact: 1 | 2 | 3;
  src: string;
  period: string | undefined;
}

export function russiaSchedule(): RuScheduled[] {
  const out: RuScheduled[] = [];
  for (const s of SERIES) {
    for (const it of s.items) {
      const { ts, allDay } = toTs(it.d, it.t ?? s.t);
      const base = it.imp ?? s.impact;
      out.push({ series: s.id, gk: s.gk, date: it.d, ts, allDay, approx: !!it.a, impact: (it.a ? Math.min(base, 2) : base) as 1 | 2 | 3, src: s.src, period: it.p });
    }
  }
  return out.sort((a, b) => a.ts - b.ts);
}

function buildAll(lang: "ru" | "en"): CalEvent[] {
  const out: CalEvent[] = [];
  for (const s of SERIES) {
    for (const it of s.items) {
      const { ts, allDay } = toTs(it.d, it.t ?? s.t);
      const q = it.p ? periodLabel(it.p, lang) : "";
      const title = `${lang === "ru" ? s.ru : s.en}${q ? `, ${q}` : ""}${it.a ? SUFFIX[lang] : ""}`;
      const extra = lang === "ru" ? it.x : it.xe;
      const flags =
        lang === "ru"
          ? `${it.a ? "Дата ориентировочная: выведена по правилу, график на этот период ещё не опубликован. " : ""}${!allDay && s.org === "Росстат" ? "Время 19:00 мск — сложившееся время выхода оперативных данных, в графике Росстата не указано. " : ""}`
          : `${it.a ? "Approximate date: derived from a rule, the schedule for this period is not published yet. " : ""}${!allDay && s.org === "Росстат" ? "19:00 Moscow time is the usual release time of the operational data; Rosstat's schedule gives none. " : ""}`;
      const base = it.imp ?? s.impact;
      out.push({
        id: eventId(ts, "RU", title),
        ts,
        allDay,
        country: "RU",
        currency: "RUB",
        event: title,
        category: "ru",
        impact: (it.a ? Math.min(base, 2) : base) as 1 | 2 | 3,
        actual: null,
        forecast: null,
        previous: null,
        unit: null,
        change: null,
        changePercentage: null,
        description: `${lang === "ru" ? s.noteRu : s.noteEn} ${extra ? extra + " " : ""}${flags}${lang === "ru" ? "Источник" : "Source"}: ${s.src}`,
        hasDesc: true,
        period: q || undefined,
        origin: s.org,
        gk: s.gk,
        tags: s.tags,
      });
    }
  }
  return out.sort((a, b) => a.ts - b.ts || b.impact - a.impact || a.event.localeCompare(b.event));
}

const built: Partial<Record<"ru" | "en", CalEvent[]>> = {};

/** Scheduled Russia events (Bank of Russia, Rosstat, Minfin) with UTC dates in [from, to] (inclusive). Russian titles for lang "ru", English otherwise. Pure, never throws. */
export function buildRussiaScheduled(from: string, to: string, lang: RuLang = "ru"): CalEvent[] {
  const l = lang === "ru" ? "ru" : "en";
  let all = built[l];
  if (!all) all = built[l] = buildAll(l);
  return all.filter((e) => {
    const d = new Date(e.ts).toISOString().slice(0, 10);
    return d >= from && d <= to;
  });
}

/* ───────────── de-duplication against the TradingView feed ───────────── */

/** gk -> the feed names that mean the same release (taken from the series table). */
const FEED_BY_GK = new Map<string, RegExp[]>();
for (const s of SERIES) {
  if (!s.feed) continue;
  const l = FEED_BY_GK.get(s.gk) ?? [];
  l.push(s.feed);
  FEED_BY_GK.set(s.gk, l);
}

/**
 * Our dates and importance are right, but the feed carries the figures (forecast / actual / previous): when the feed has the same Russian
 * release on the same UTC day, the feed's event stays and ours is dropped. Feed events are the raw (English) ones.
 */
export function dropCoveredByFeed(layer: readonly CalEvent[], feed: readonly CalEvent[]): CalEvent[] {
  const ru = feed.filter((f) => f.country === "RU" && f.category !== "ru");
  if (ru.length === 0) return layer.slice();
  const day = (ts: number) => new Date(ts).toISOString().slice(0, 10);
  const have = ru.map((f) => ({ d: day(f.ts), name: f.event.trim() }));
  return layer.filter((e) => {
    const res = e.gk ? FEED_BY_GK.get(e.gk) : undefined;
    if (!res) return true;
    const d = day(e.ts);
    return !have.some((h) => h.d === d && res.some((re) => re.test(h.name)));
  });
}
